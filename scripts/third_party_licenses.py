#!/usr/bin/env python3
"""Generuje THIRD_PARTY_LICENSES.md: licencje bibliotek wchodzących do programu.

Uruchom z katalogu repozytorium: python3 scripts/third_party_licenses.py
Bierze tylko zależności zwykłe (bez dev- i build-dependencies) dla wszystkich platform.
"""
import json, os, re, subprocess, sys
from collections import defaultdict

meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"]))
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
root = meta["resolve"]["root"]

# zależności osiągalne krawędziami „normal” od korzenia
seen, stack = set(), [root]
while stack:
    cur = stack.pop()
    for d in nodes[cur]["deps"]:
        if any(k["kind"] in (None, "normal") for k in d["dep_kinds"]) and d["pkg"] not in seen:
            seen.add(d["pkg"]); stack.append(d["pkg"])

LIC_RE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE|OFL|UFL)", re.I)

def license_files(p):
    d = os.path.dirname(p["manifest_path"])
    out = []
    for base in [d, os.path.join(d, "fonts"), os.path.join(d, "vendor")]:
        if not os.path.isdir(base):
            continue
        for f in sorted(os.listdir(base)):
            path = os.path.join(base, f)
            if os.path.isfile(path) and (LIC_RE.match(f) or f.lower().endswith("license.txt")):
                out.append(path)
    if p.get("license_file"):
        lf = os.path.join(d, p["license_file"])
        if os.path.isfile(lf) and lf not in out:
            out.append(lf)
    return out

# wzorcowe teksty licencji SPDX, zebrane z plików, które biblioteki dołączają
STD = {}
def remember(spdx, path):
    if spdx not in STD:
        STD[spdx] = open(path, encoding="utf-8", errors="replace").read().strip()

# teksty wzorcowe, których żadna biblioteka nie dołącza (scripts/licenses/<SPDX>.txt)
REF_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "licenses")
for f in sorted(os.listdir(REF_DIR)):
    if f.endswith(".txt"):
        remember(f[:-4], os.path.join(REF_DIR, f))

by_text = defaultdict(list)   # treść pliku licencji -> [crate]
no_file = defaultdict(list)   # wyrażenie licencji -> [crate]
for pid in sorted(seen, key=lambda i: (pkgs[i]["name"], pkgs[i]["version"])):
    p = pkgs[pid]
    name = f'{p["name"]} {p["version"]}'
    files = license_files(p)
    for f in files:
        fn = os.path.basename(f).upper()
        if "APACHE" in fn: remember("Apache-2.0", f)
        elif "MIT" in fn: remember("MIT", f)
        elif fn.startswith("OFL"): remember("OFL-1.1", f)
        elif "BOOST" in fn or "BSL" in fn: remember("BSL-1.0", f)
        elif "ZLIB" in fn: remember("Zlib", f)
        elif "UNICODE" in fn: remember("Unicode-3.0", f)
        elif fn.startswith("UNLICENSE"): remember("Unlicense", f)
    if files:
        for f in files:
            txt = open(f, encoding="utf-8", errors="replace").read().strip()
            by_text[txt].append((name, p.get("license") or "?", os.path.basename(f)))
    else:
        no_file[p.get("license") or "?"].append((name, ", ".join(p.get("authors") or []) or "autorzy projektu " + p["name"]))

out = []
out.append("# Licencje bibliotek zewnętrznych / Third-party licenses\n")
out.append("Przeglądarka MRI korzysta z poniższych bibliotek open source. Ten plik jest generowany skryptem `scripts/third_party_licenses.py`.\n")
out.append("MRI Viewer uses the open-source libraries listed below. This file is generated by `scripts/third_party_licenses.py`.\n")
out.append(f"\nLiczba bibliotek / number of crates: {len(seen)}\n")
out.append("\n## Biblioteki bez własnego pliku licencji / Crates without a bundled license file\n")
out.append("Obowiązuje standardowy tekst licencji podany na końcu pliku; prawa autorskie należą do wymienionych autorów.\n")
for expr in sorted(no_file):
    out.append(f"\n### {expr}\n")
    for name, authors in no_file[expr]:
        out.append(f"- {name} — © {authors}")
out.append("\n\n## Teksty licencji dołączone przez biblioteki / License texts bundled with crates\n")
for txt, users in sorted(by_text.items(), key=lambda kv: kv[1][0][0]):
    names = ", ".join(sorted({u[0] for u in users}))
    exprs = ", ".join(sorted({u[1] for u in users}))
    out.append(f"\n### {names}\n\nLicencja / License: {exprs} ({users[0][2]})\n\n````text\n{txt}\n````\n")
out.append("\n## Standardowe teksty licencji / Standard license texts\n")
for spdx in sorted(STD):
    out.append(f"\n### {spdx}\n\n````text\n{STD[spdx]}\n````\n")
# wyrażenie jest pokryte, gdy choć jedna z licencji do wyboru (OR) ma tekst wzorcowy
missing = sorted(e for e in no_file if not any(part.strip("() ") in STD for part in e.split(" OR ")))
if missing:
    out.append("\nWyrażenia licencji bez dołączonego tekstu wzorcowego / expressions without a bundled reference text: " + "; ".join(missing) + "\n")
open("THIRD_PARTY_LICENSES.md", "w", encoding="utf-8").write("\n".join(out))
print(len(seen), "crates;", len(by_text), "distinct bundled texts;", "std:", sorted(STD), file=sys.stderr)
